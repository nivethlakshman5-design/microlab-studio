import { writeFile } from 'node:fs/promises';

const raw = process.env.MICROLAB_PUBLIC_URL?.trim();
if (!raw) {
  console.error('Set MICROLAB_PUBLIC_URL to the public HTTPS production URL before packaging native apps.');
  process.exit(1);
}

let url;
try {
  url = new URL(raw);
} catch {
  console.error('MICROLAB_PUBLIC_URL must be a valid absolute URL.');
  process.exit(1);
}
if (url.protocol !== 'https:') {
  console.error('MICROLAB_PUBLIC_URL must use HTTPS.');
  process.exit(1);
}
if (url.hostname === 'microlab-studio.higgsfield.app' || url.hostname.endsWith('.higgsfield.app')) {
  console.error('Do not package a Higgsfield-hosted URL; the current hosted deployment requires authentication for logged-out visitors. Use a public production endpoint.');
  process.exit(1);
}

await writeFile(
  new URL('../native-shell/app-config.js', import.meta.url),
  `// Generated by scripts/configure-native-endpoint.mjs. Do not commit production secrets here.\nwindow.MICROLAB_PUBLIC_URL = ${JSON.stringify(url.href.replace(/\/$/, ''))};\n`,
);
console.log(`Configured native shells for ${url.origin}`);
